// Shared by the browser and build pipeline. Never infer a Korean verb from a
// bare final 다: 캐나다, 혼다 and 프라다 are names, not sentence endings.
export function executiveBulletCopy(value = "") {
  return String(value ?? "")
    .replace(/할 수 없습니다(?=[.!?。]|\s*$)/g, "불가")
    .replace(/할 수 있습니다(?=[.!?。]|\s*$)/g, "가능")
    .replace(/해야 합니다(?=[.!?。]|\s*$)/g, "필요")
    .replace(/필요가 있습니다(?=[.!?。]|\s*$)/g, "필요")
    .replace(/가능성이 (?:큽니다|높습니다)(?=[.!?。]|\s*$)/g, "가능성 높음")
    .replace(/가능성이 낮습니다(?=[.!?。]|\s*$)/g, "가능성 낮음")
    .replace(/아닙니다(?=[.!?。]|\s*$)/g, "아님")
    .replace(/봅니다(?=[.!?。]|\s*$)/g, "판단")
    .replace(/([가-힣]{2,})(?:되었습니다|했습니다|됐습니다|합니다|됩니다)(?=[.!?。]|\s*$)/g, "$1")
    .replace(/([가-힣])했습니다(?=[.!?。]|\s*$)/g, "$1했음")
    .replace(/([가-힣])되었습니다(?=[.!?。]|\s*$)/g, "$1되었음")
    .replace(/([가-힣])됐습니다(?=[.!?。]|\s*$)/g, "$1됐음")
    .replace(/([가-힣]+)입니다(?=[.!?。]|\s*$)/g, "$1")
    .replace(/([가-힣]+)집니다(?=[.!?。]|\s*$)/g, "$1짐")
    .replace(/([가-힣]+)립니다(?=[.!?。]|\s*$)/g, "$1림")
    .replace(/([가-힣]+)듭니다(?=[.!?。]|\s*$)/g, "$1듦")
    .replace(/([가-힣]+)납니다(?=[.!?。]|\s*$)/g, "$1남")
    .replace(/([가-힣]+)줍니다(?=[.!?。]|\s*$)/g, "$1줌")
    .replace(/([가-힣]+)둡니다(?=[.!?。]|\s*$)/g, "$1둠")
    .replace(/습니다(?=[.!?。]|\s*$)/g, "음")
    .replace(/(^|\s)(다릅니다|빠릅니다|큽니다|갑니다)(?=[.!?。]|\s*$)/g, (_, gap, word) => gap + ({ 다릅니다: "다름", 빠릅니다: "빠름", 큽니다: "큼", 갑니다: "감" })[word])
    .replace(/([가-힣]{2,})(?:한다|된다|했다|됐다)(?=[.!?。]|\s*$)/g, "$1")
    .replace(/(^|\s)(있다|없다|좋다|크다|올랐다|간다|산다|먹는다|팔린다|다르다|빠르다)(?=[.!?。]|\s*$)/g, (_, gap, word) => gap + ({ 있다: "있음", 없다: "없음", 좋다: "좋음", 크다: "큼", 올랐다: "올랐음", 간다: "감", 산다: "삼", 먹는다: "먹음", 팔린다: "팔림", 다르다: "다름", 빠르다: "빠름" })[word])
    .replace(/([가-힣])[.。]+\s+(?=[가-힣A-Za-z0-9])/g, "$1 · ")
    .replace(/([A-Za-z\u3131-\u318e\uac00-\ud7a3\d%)\]"'”’])[.。]+(?=\s*$)/g, "$1")
    .replace(/\s*·\s*·\s*/g, " · ");
}
